#!/usr/bin/env node
// Per-component Docker build contexts cannot COPY a shared parent directory.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'src/tls-trust-policy.ts'), 'utf8');
const js = '// Generated by scripts/security/generate-trust-policy.cjs; do not edit.\n'
  + ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
  }).outputText;
const hashes = [...source.matchAll(/'([a-f0-9]{64})'/g)].map(match => match[1]).join('\n') + '\n';
const files = {
  'node-trust.cjs': js,
  'distrusted-spki.txt': hashes,
  'filter-ca-store.sh': fs.readFileSync(path.join(__dirname, 'filter-ca-store.sh'), 'utf8'),
  'install-system-trust.sh': fs.readFileSync(path.join(__dirname, 'install-system-trust.sh'), 'utf8'),
  'install-node-trust.sh': fs.readFileSync(path.join(__dirname, 'install-node-trust.sh'), 'utf8'),
};
let mismatched = false;
for (const component of ['agent', 'api-proxy', 'cli-proxy', 'squid', 'build-tools', 'gh-aw-node', 'router', 'dind-ubuntu', 'trust']) {
  const dir = path.join(root, 'containers', component, ...(component === 'trust' ? [] : ['trust']));
  for (const [name, content] of Object.entries(files)) {
    const dest = path.join(dir, name);
    if (['squid', 'router', 'build-tools'].includes(component)
        && ['node-trust.cjs', 'install-node-trust.sh'].includes(name)) {
      if (!process.argv.includes('--check') && fs.existsSync(dest)) fs.unlinkSync(dest);
      continue;
    }
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== content) {
        console.error(`Out-of-sync trust policy: ${path.relative(root, dest)}`);
        mismatched = true;
      }
    } else {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(dest, content);
    }
  }
}
if (mismatched) process.exitCode = 1;
